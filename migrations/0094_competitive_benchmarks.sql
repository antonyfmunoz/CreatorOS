CREATE TABLE "competitive_benchmark_definitions" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "business_id" uuid NOT NULL REFERENCES "businesses"("id") ON DELETE cascade,
  "family" text NOT NULL,
  "name" text NOT NULL,
  "version" integer NOT NULL DEFAULT 1,
  "target_user" text NOT NULL,
  "workflow" text NOT NULL,
  "comparison_products" json NOT NULL DEFAULT '[]'::json,
  "output_specification" json NOT NULL DEFAULT '{}'::json,
  "rubric" json NOT NULL DEFAULT '{}'::json,
  "source_references" json NOT NULL DEFAULT '[]'::json,
  "status" text NOT NULL DEFAULT 'draft',
  "created_by_user_id" integer NOT NULL REFERENCES "users"("id") ON DELETE restrict,
  "locked_by_user_id" integer REFERENCES "users"("id") ON DELETE restrict,
  "locked_at" timestamp,
  "created_at" timestamp NOT NULL DEFAULT now(),
  "updated_at" timestamp NOT NULL DEFAULT now(),
  CONSTRAINT "competitive_benchmark_definition_version_unique" UNIQUE("business_id","family","version"),
  CONSTRAINT "competitive_benchmark_definition_status_check" CHECK("status" IN ('draft','locked','retired'))
);

CREATE TABLE "competitive_benchmark_runs" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "definition_id" uuid NOT NULL REFERENCES "competitive_benchmark_definitions"("id") ON DELETE restrict,
  "business_id" uuid NOT NULL REFERENCES "businesses"("id") ON DELETE cascade,
  "operator_user_id" integer NOT NULL REFERENCES "users"("id") ON DELETE restrict,
  "implementation" text NOT NULL,
  "comparison_product" text,
  "status" text NOT NULL DEFAULT 'in_progress',
  "environment" json NOT NULL DEFAULT '{}'::json,
  "active_time_ms" integer,
  "elapsed_time_ms" integer,
  "application_count" integer,
  "export_count" integer,
  "upload_count" integer,
  "manual_handoff_count" integer,
  "action_count" integer,
  "retry_count" integer,
  "failure_count" integer,
  "unrecoverable_error_count" integer,
  "output_quality_score" double precision,
  "safety_score" double precision,
  "reliability_score" double precision,
  "accessibility_score" double precision,
  "notes" text NOT NULL DEFAULT '',
  "evidence" json NOT NULL DEFAULT '[]'::json,
  "started_at" timestamp NOT NULL DEFAULT now(),
  "completed_at" timestamp,
  "created_at" timestamp NOT NULL DEFAULT now(),
  "updated_at" timestamp NOT NULL DEFAULT now(),
  CONSTRAINT "competitive_benchmark_run_implementation_check" CHECK("implementation" IN ('creativesos','comparison')),
  CONSTRAINT "competitive_benchmark_run_status_check" CHECK("status" IN ('in_progress','completed','failed','invalid'))
);
CREATE INDEX "competitive_benchmark_run_status_idx" ON "competitive_benchmark_runs"("definition_id","status");

CREATE TABLE "competitive_benchmark_assessments" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
  "definition_id" uuid NOT NULL REFERENCES "competitive_benchmark_definitions"("id") ON DELETE restrict,
  "business_id" uuid NOT NULL REFERENCES "businesses"("id") ON DELETE cascade,
  "creativesos_run_id" uuid NOT NULL REFERENCES "competitive_benchmark_runs"("id") ON DELETE restrict,
  "comparison_run_id" uuid NOT NULL REFERENCES "competitive_benchmark_runs"("id") ON DELETE restrict,
  "state" text NOT NULL,
  "quality_comparable" boolean NOT NULL,
  "active_time_reduction_bps" integer NOT NULL,
  "handoff_reduction_bps" integer NOT NULL,
  "reviewer_user_id" integer NOT NULL REFERENCES "users"("id") ON DELETE restrict,
  "reviewer_note" text NOT NULL,
  "assessed_at" timestamp NOT NULL DEFAULT now(),
  CONSTRAINT "competitive_benchmark_assessment_pair_unique" UNIQUE("creativesos_run_id","comparison_run_id"),
  CONSTRAINT "competitive_benchmark_assessment_state_check" CHECK("state" IN ('parity_failed','parity_met','connected_advantage_proven'))
);
